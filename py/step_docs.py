def model_page(model: dict) -> str:
    rows = "\n".join(f"| `{c}` | {v['comment']} |" for c, v in sorted(model["concepts"].items()))
    return f"""# Model

## Concepts

| Concept | Meaning |
|---|---|
{rows}

## Simple view

Classes in dark orange. Black arrows are the asserted properties, dashed black arrows their inverses.
Red arcs are the links the reasoner derives from the role chains.

{figure("01_simple_model", "Simple view")}
## Full semantics

The same model in the AMT vocabulary. Amber pills are roles (domain to range). White boxes are axioms.
A dashed outline marks a role that exists only as the inverse of another role; a red outline marks a
role that is derived by reasoning.

{figure("02_full_semantics", "Full semantics")}
Read it from the left: the asserted roles and their inverses; the role chains that compose the roles
along the chain direction (the numbers give the order of the antecedents); the derived roles with
their inverses; and the generic role `reaches` that subsumes all three.
"""


def vocabulary_page(model: dict) -> str:
    kinds, partner = classify(model), partners(model)
    made_by = {cons: (axiom, ante) for axiom, ante, cons, _ in model["chains"]}
    out = ["# Vocabulary\n",
           "Namespace `http://example.org/mini-amt/` (placeholder, to be replaced by a persistent IRI).\n",
           "## Concepts\n"]
    for c, v in sorted(model["concepts"].items()):
        out.append(f"### mini:{c}\n\n{v['comment']}\n")
    out.append("## Roles\n\nGrouped by how a role comes into being. *Limit* is what the role does not "
               "say, and that matters archaeologically.\n")
    for kind in KIND_ORDER:
        group = sorted(r for r, k in kinds.items() if k == kind)
        if not group:
            continue
        out.append(f"### {kind[0].upper() + kind[1:]}\n")
        for role in group:
            r = model["roles"][role]
            lines = [f"#### mini:{role}\n", f"{r['definition']}\n", f"- **Limit:** {r['scope']}"]
            if r["domain"]:
                lines.append(f"- **Domain to range:** `{r['domain']}` to `{r['range']}`")
            if role in partner:
                lines.append(f"- **Inverse:** `{partner[role]}`")
            if role in made_by:
                axiom, ante = made_by[role]
                lines.append(f"- **Derived by:** `{axiom}` (`{' o '.join(ante)}`)")
            out.append("\n".join(lines) + "\n")
    out.append("## Axioms\n\n### Inverse axioms\n\n| Axiom | Antecedent | Inverse |\n|---|---|---|")
    out += [f"| `{a}` | `{x}` | `{y}` |" for a, x, y in model["inverses"]]
    out.append("\nThe weight of the antecedent edge is copied to the inverse edge.\n")
    out.append("### Role chains\n\n| Axiom | Antecedents (in order) | Consequent | Logic |\n|---|---|---|---|")
    out += [f"| `{a}` | `{' o '.join(ante)}` | `{c}` | `{lg}` (placeholder) |" for a, ante, c, lg in model["chains"]]
    out.append("\n### Subsumption axioms\n\n| Axiom | Sub-role | Super-role |\n|---|---|---|")
    out += [f"| `{a}` | `{s}` | `{p}` |" for a, s, p in model["subs"]]
    return "\n".join(out) + "\n"


def reasoning_page(model: dict, state: dict) -> str:
    derived = [(c, ante) for _, ante, c, _ in model["chains"]]
    partner = partners(model)
    reading = []
    for cons, ante in sorted(derived, key=lambda t: (len(t[1]), t[0])):
        f, b = model["roles"][cons], model["roles"][partner[cons]]
        reading.append(f"| `{cons}` | {f['definition']} | `{partner[cons]}` | {plain(b['definition'])} |")
    scope = []
    for cons, _ in sorted(derived, key=lambda t: (len(t[1]), t[0])):
        f, b = model["roles"][cons], model["roles"][partner[cons]]
        scope.append(f"| `{cons}` | {f['scope']} |\n| `{partner[cons]}` | {b['scope']} |")
    kinds = classify(model)
    rows = [f"| `{a}` --`{role}`--> `{b}` | {e['weight']:.2f} | {', '.join(f'`{p}`' for p in e['provenance']) or 'asserted'} |"
            for (role, a, b), e in sorted(state.items(), key=lambda kv: (KIND_ORDER.index(kinds[kv[0][0]]), kv[0]))]
    return f"""# Reasoning

## Why inverses are needed

{T.WHY_INVERSES}

## Reasoning properties, read from both ends

The three derived roles ("`>>`") and their inverses ("`<<`"). *Associated with* always means connected
through the chain, nothing more.

| Forward (`>>`) | Reads as | Inverse (`<<`) | Reads as |
|---|---|---|---|
{chr(10).join(reading)}

The limits, role by role:

| Role | Limit (what it does not say) |
|---|---|
{chr(10).join(scope)}

All three forward roles are subsumed by the generic role `reaches` (and `reachedBy` for the inverses),
so one query finds every derived association.

{figure("04_reasoning_both", "Reasoning properties in both directions")}
## A worked chain

One abstract individual per concept. Only the three weighted edges of the source direction are asserted;
everything else below is derived. The weights are arbitrary placeholders, and the logic operator is
`GoedelLogic` (minimum) as a placeholder: the chain is as strong as its weakest link.

{figure("03_toy_reasoning", "Toy chain")}
| Edge | Weight | Source |
|---|---|---|
{chr(10).join(rows)}

## What the reasoning does and does not do

{T.CAVEATS}
"""


