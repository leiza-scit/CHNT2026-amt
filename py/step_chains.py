"""Step "chains": three real chains from the CHNT data, as hextuples, with the reasoning of two models.

Reads   data/chains-source.csv   the source strings of the chains (potform, centre) as they stand in the data
Writes  dist/chains.ttl          the hextuples of model M1: fw:hasDegreeOfConnection, fw:hasType, fw:hasMethod
                                 (computed by weights.py) and the source string as fw:TextEvidence
        dist/chains-with-model.ttl  ontology M1 + chains.ttl in one file (input for the AMT engine and the runner)
        dist/chains-reasoned.csv every edge of the three reasoning runs (with type and method)
        dist/chains-report.md    the comparison of the models, human-readable

Models
  M1  ontology/mini-amt.ttl            hasProductionCentre is asserted (as in the data export)
  M2  ontology/variant-b-derived.ttl   hasProductionCentre is derived: createdBy (crisp) o worksAt
Runs
  M1 with the logic of the ontology (ProductLogic), M1 with GoedelLogic, M2 with ProductLogic.

The exported centre weights of the source (column exported_centre_weights) must equal the weights
that the rule computes; the step fails otherwise. The written Turtle is read back and must give the
source strings again (evidence node, shared by all statements of one string). If the AMT engine
(0.6.0 or newer) is installed, the three runs are repeated with it and compared edge by edge,
including type and method.
"""
from __future__ import annotations

import csv
import re
import sys
import unicodedata
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import weights as W  # noqa: E402
from mini_amt_utils import DIST, ONTOLOGY, ROOT, load_graph, local, read_model  # noqa: E402
from reference_reasoner import reason  # noqa: E402

SOURCE = ROOT / "data" / "chains-source.csv"
VARIANT = ROOT / "ontology" / "variant-b-derived.ttl"

HEADER = """@prefix amt:     <http://academic-meta-tool.xyz/vocab#> .
@prefix rdf:     <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .
@prefix rdfs:    <http://www.w3.org/2000/01/rdf-schema#> .
@prefix mini:    <http://example.org/mini-amt/> .
@prefix fw:      <http://w3id.org/fw_ontology/> .

# Generated by main.py (step: chains) from data/chains-source.csv. Do not edit by hand.
# Every weighted statement is a hextuple with the terms of the FW ontology: rdf:subject,
# rdf:predicate, rdf:object, fw:hasDegreeOfConnection (the same as amt:weight), fw:hasType
# (fw:Uncertainty, fw:Vagueness or fw:FuzzinessWobbliness; absent for a certain statement, which
# AMT reads as fw:Vagueness) and fw:hasMethod (fw:EqualShareRule). fw:derivedFrom points to the
# source string (fw:TextEvidence); the statements of one string share one evidence node.
# mini:attributedTo is the crisp carrier-actor link; only model M2 uses it.
"""


def slug(text: str) -> str:
    t = unicodedata.normalize("NFKD", text.replace("ä", "ae").replace("ö", "oe").replace("ü", "ue"))
    return re.sub(r"[^a-z0-9]+", "_", t.encode("ascii", "ignore").decode().lower()).strip("_")


def evidence_id(context: str, text: str) -> str:
    """IRI part of the evidence node of a source string; a '?' is spelt out so that '32' and '32?' differ."""
    kind = "potform" if context.endswith("potform") else "centre"
    return f"ev_{kind}_{slug(text.replace('?', ' q '))}"


def read_source() -> list[dict]:
    with SOURCE.open(encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh))
    for r in rows:
        computed = [e["weight"] for e in W.edges_for(r["centre_text"], "informationcarrier--productioncentre")]
        exported = [float(x) for x in r["exported_centre_weights"].split(";")]
        if sorted(computed) != sorted(exported):
            raise AssertionError(f"carrier {r['carrier_id']}: rule gives {computed}, export has {exported}")
    return rows


def build_edges(rows: list[dict]) -> tuple[list[dict], dict]:
    """Edges of model M1 (hextuple payloads) and the labels of all nodes."""
    nodes, edges, seen = {}, [], set()

    def add(role, a, b, payload, ctx):
        key = (role, a, b)
        if key not in seen:                      # the same potter appears with several carriers
            seen.add(key)
            edges.append({"role": role, "from": a, "to": b, "context": ctx,
                          "evidence": evidence_id(ctx, payload["source"]), **payload})

    for r in rows:
        ic, ae = "ic_" + r["carrier_id"], "ae_" + slug(r["potter"])
        nodes[ic] = ("InformationCarrier", f"Carrier {r['carrier_id']}")
        nodes[ae] = ("Actor", r["potter"])
        for e in W.edges_for(r["potform_text"], "informationcarrier--potform"):
            pf = "pf_" + slug(e["entity"])
            nodes[pf] = ("Potform", "Potform " + e["entity"])
            add("hasType", ic, pf, e, "informationcarrier--potform")
        for ctx, role, owner in (("informationcarrier--productioncentre", "hasProductionCentre", ic),
                                 ("actor--productioncentre", "worksAt", ae)):
            for e in W.edges_for(r["centre_text"], ctx):
                pc = "pc_" + slug(e["entity"])
                nodes[pc] = ("ProductionCentre", e["entity"])
                add(role, owner, pc, e, ctx)
    return sorted(edges, key=lambda e: (e["role"], e["from"], e["to"])), nodes


def statement_ttl(e: dict) -> str:
    """One hextuple (or a plain quadruple if the edge has neither type, method nor evidence)."""
    parts = [f"fw:hasDegreeOfConnection {e['weight']}"]
    if e.get("type"):
        parts.append(f"fw:hasType fw:{e['type']}")
    if e.get("method"):
        parts.append(f"fw:hasMethod fw:{e['method']}")
    if e.get("evidence"):
        parts.append(f"fw:derivedFrom mini:{e['evidence']}")
    return (f"[] rdf:subject mini:{e['from']} ; rdf:predicate mini:{e['role']} ; rdf:object mini:{e['to']} ;\n"
            f"   {' ; '.join(parts)} .")


def nodes_ttl(nodes: dict) -> str:
    return "\n".join(f'mini:{key} amt:instanceOf mini:{concept} ; rdfs:label "{label}" .'
                     for key, (concept, label) in sorted(nodes.items()))


def evidence_ttl(edges: list[dict]) -> str:
    """One fw:TextEvidence node per source string; all statements of the string point to it."""
    seen = {e["evidence"]: e["source"] for e in edges if e.get("evidence")}
    return "\n".join(f'mini:{ev} a fw:TextEvidence ; fw:sourceString "{text}" .' for ev, text in sorted(seen.items()))


def write_ttl(edges, nodes, rows) -> None:
    out = [HEADER, nodes_ttl(nodes), ""]
    for r in rows:
        out.append(f"mini:ic_{r['carrier_id']} mini:attributedTo mini:ae_{slug(r['potter'])} .")
    out += ["", evidence_ttl(edges), ""]
    out += [statement_ttl(e) for e in edges]
    (DIST / "chains.ttl").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")


FW_NS = "http://w3id.org/fw_ontology/"
MIN_ENGINE = (0, 6, 0)                       # first AMT.engine that reads fw:hasType, fw:hasMethod and fw:derivedFrom


def check_roundtrip(res: dict) -> int:
    """Read dist/chains.ttl back: every statement must lead to its source string, and weight, type and
    method must be the ones the rule gives for that string. Returns the number of statements checked."""
    from rdflib import Namespace, RDF
    fw, amt_ns = Namespace(FW_NS), Namespace("http://academic-meta-tool.xyz/vocab#")
    g = load_graph(DIST / "chains.ttl")
    entity_of = {key: (label[len("Potform "):] if concept == "Potform" else label)
                 for key, (concept, label) in res["nodes"].items()}
    groups: dict = {}                                    # (subject, evidence node) -> [(object, weight, type, method)]
    for s in g.subjects(RDF.subject, None):
        ev = g.value(s, fw.derivedFrom)
        if ev is None or (ev, RDF.type, fw.TextEvidence) not in g:
            raise AssertionError(f"statement without text evidence: {s}")
        if g.value(s, amt_ns.weight) is not None:
            raise AssertionError("amt:weight and fw:hasDegreeOfConnection should not both be written")
        typ, meth = g.value(s, fw.hasType), g.value(s, fw.hasMethod)
        groups.setdefault((local(g.value(s, RDF.subject)), local(ev)), []).append(
            (entity_of[local(g.value(s, RDF.object))], float(g.value(s, fw.hasDegreeOfConnection)),
             local(typ) if typ else None, local(meth)))
    strings = {str(g.value(ev, fw.sourceString)) for ev in g.subjects(RDF.type, fw.TextEvidence)}
    wanted = {r[c] for r in res["rows"] for c in ("potform_text", "centre_text")}
    if strings != wanted:
        raise AssertionError(f"evidence strings differ from the source: {sorted(strings ^ wanted)}")
    n = 0
    for (subject, ev), items in sorted(groups.items()):
        text = str(g.value(next(g.subjects(RDF.type, fw.TextEvidence) if False else
                               (x for x in g.subjects(RDF.type, fw.TextEvidence) if local(x) == ev)), fw.sourceString))
        st = W.parse(text)
        for entity, weight, typ, meth in items:
            if (weight, typ, meth) != (st.weight, st.fw_type, W.FW_METHOD):
                raise AssertionError(f"{subject}: {entity!r} from {text!r} has {(weight, typ, meth)}, rule gives "
                                     f"{(st.weight, st.fw_type, W.FW_METHOD)}")
        if sorted(i[0] for i in items) != sorted(st.entities):
            raise AssertionError(f"{subject}: entities {sorted(i[0] for i in items)} differ from {text!r}")
        # counter-check without the evidence: weight, type and number of edges rebuild the string
        back = W.reconstruct([{"entity": i[0], "weight": i[1], "type": i[2]} for i in items])
        if sorted(W.parse(back).entities) != sorted(st.entities) or W.parse(back).weight != st.weight:
            raise AssertionError(f"{subject}: {text!r} is not rebuilt from weight and type ({back!r})")
        n += len(items)
    return n


def _model_text(path: Path, logic: str) -> str:
    text = path.read_text(encoding="utf-8")
    return re.sub(r"(amt:logic\s+)amt:ProductLogic", rf"\1amt:{logic}", text)


def engine_inputs(res: dict) -> dict:
    """The three runs as Turtle files for the AMT engine: model text, nodes, evidence and statements."""
    body = "\n".join([HEADER, nodes_ttl(res["nodes"]), "", evidence_ttl(res["edges"]), ""])
    m1_statements = "\n".join(statement_ttl(e) for e in res["edges"])
    m2_statements = "\n".join(statement_ttl(e) for e in res["edges"] if e["role"] != "hasProductionCentre")
    created = "\n".join(f"[] rdf:subject mini:{a} ; rdf:predicate mini:{role} ; rdf:object mini:{b} ; amt:weight 1.0 ."
                        for role, a, b, *_ in (e for e in res["m2_edges"] if e[0] == "createdBy"))
    return {"M1 product": _model_text(ONTOLOGY, "ProductLogic") + "\n" + body + m1_statements + "\n",
            "M1 goedel": _model_text(ONTOLOGY, "GoedelLogic") + "\n" + body + m1_statements + "\n",
            "M2 product": VARIANT.read_text(encoding="utf-8") + "\n" + body + m2_statements + "\n" + created + "\n"}


def engine_check(res: dict) -> int:
    """Run the three models with the AMT engine and compare every edge (weight, type, method of derived edges)."""
    try:
        import amt
        from amt import do_reasoning, load_amt, validate_against_shapes
    except ImportError:
        print("AMT engine not installed - cross-check skipped (pip install -r requirements.txt)")
        return 0
    version = tuple(int(x) for x in str(getattr(amt, "__version__", "0")).split(".")[:3] if x.isdigit())
    if version < MIN_ENGINE:
        print(f"AMT engine {amt.__version__} is installed; type and method need {'.'.join(map(str, MIN_ENGINE))} or newer "
              "- cross-check skipped (pip install -r requirements.txt)")
        return 0
    VAG = "Vagueness"
    problems = []
    for name, text in engine_inputs(res).items():
        path = DIST / f"engine-input-{name.replace(' ', '-')}.ttl"
        path.write_text(text, encoding="utf-8", newline="\n")
        data = load_amt(str(path))
        if name != "M1 goedel":                      # the logic does not change the shapes
            shapes = validate_against_shapes(path)
            focus = sorted({v["focus"] for v in shapes.violations})
            print(f"SHACL (engine shapes), {name}: " + ("conforms" if shapes.conforms else
                  f"{len(shapes.violations)} violation(s) at {', '.join(focus)}"))
        out = {(local(e["role"]), local(e["from"]), local(e["to"])): e
               for e in do_reasoning(data["edges"], data["axioms"])}
        ref = res["runs"][name]
        for key in sorted(set(ref) ^ set(out)):
            problems.append(f"{name}: {key} only in {'reference' if key in ref else 'engine'}")
        for key in sorted(set(ref) & set(out)):
            r, e = ref[key], out[key]
            et = local(e["type"]) if e.get("type") else VAG
            if abs(r["weight"] - e["weight"]) > 1e-9:
                problems.append(f"{name}: {key} weight {r['weight']:.6f} (reference) against {e['weight']:.6f} (engine)")
            if (r["type"] or VAG) != et:
                problems.append(f"{name}: {key} type {r['type'] or VAG} (reference) against {et} (engine)")
            if r["inferred"] and (r["method"] or "") != (local(e["method"]) if e.get("method") else ""):
                problems.append(f"{name}: {key} method {r['method']} (reference) against {e.get('method')} (engine)")
    if problems:
        print("MISMATCH engine vs reference")
        for line in problems[:20]:
            print("  " + line)
        if len(problems) > 20:
            print(f"  ... and {len(problems) - 20} more")
        return 1
    n = sum(len(s) for s in res["runs"].values())
    print(f"AMT engine agrees with the reference reasoner on all {n} edges of the three runs (weight, type, method)")
    return 0


def with_logic(model: dict, logic: str) -> dict:
    return {**model, "chains": [(a, ante, c, logic) for a, ante, c, _ in model["chains"]]}


def run() -> dict:
    rows = read_source()
    edges, nodes = build_edges(rows)
    m1_edges = [(e["role"], e["from"], e["to"], e["weight"], e["type"]) for e in edges]
    m1 = read_model(load_graph(ONTOLOGY))
    m2 = read_model(load_graph(VARIANT))
    m2_edges = [t for t in m1_edges if t[0] != "hasProductionCentre"]
    m2_edges += [("createdBy", "ic_" + r["carrier_id"], "ae_" + slug(r["potter"]), 1.0, None) for r in rows]
    runs = {"M1 product": reason(m1, m1_edges), "M1 goedel": reason(with_logic(m1, "GoedelLogic"), m1_edges),
            "M2 product": reason(m2, m2_edges)}
    return {"rows": rows, "edges": edges, "nodes": nodes, "runs": runs, "m2_edges": m2_edges}


def comparison(res: dict) -> list[dict]:
    """The derived pairs of every chain under the three runs (None where a run has no such edge)."""
    r1, rg, r2 = res["runs"]["M1 product"], res["runs"]["M1 goedel"], res["runs"]["M2 product"]
    out = []
    for (role, a, b) in sorted(k for k, v in r1.items() if k[0] in ("potformToCentre", "carrierToActor", "potformToActor")):
        m2role = {"carrierToActor": "createdBy"}.get(role, role)
        out.append({"relation": role, "from": a, "to": b, "m1_product": r1[(role, a, b)]["weight"],
                    "m1_goedel": rg[(role, a, b)]["weight"],
                    "m2_product": r2.get((m2role, a, b), {}).get("weight")})
    for (role, a, b), e in sorted(r1.items()):
        if role == "hasProductionCentre":
            out.append({"relation": "carrierToCentre", "from": a, "to": b, "m1_product": e["weight"],
                        "m1_goedel": e["weight"], "m2_product": r2.get(("carrierToCentre", a, b), {}).get("weight")})
    return out


def main() -> int:
    DIST.mkdir(exist_ok=True)
    res = run()
    write_ttl(res["edges"], res["nodes"], res["rows"])
    with (DIST / "chains-reasoned.csv").open("w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["run", "role", "from", "to", "weight", "kind", "type", "method"])
        for run_name, state in res["runs"].items():
            for (role, a, b), e in sorted(state.items()):
                w.writerow([run_name, role, a, b, f"{e['weight']:.4f}", "derived" if e["inferred"] else "asserted",
                            e["type"] or "Vagueness", e["method"] or ""])
    lines = ["# Chains: M1 (product, Goedel) against M2 (product)", "",
             "| Relation | From | To | M1 product | M1 Goedel | M2 product |", "|---|---|---|---|---|---|"]
    for c in comparison(res):
        m2 = "-" if c["m2_product"] is None else f"{c['m2_product']:.3f}"
        lines.append(f"| {c['relation']} | {c['from']} | {c['to']} | {c['m1_product']:.3f} | {c['m1_goedel']:.3f} | {m2} |")
    (DIST / "chains-report.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    unlisted = sum(1 for e in res["edges"] if not e["listed"])
    print(f"chains: {len(res['rows'])} carriers, {len(res['edges'])} hextuples ({unlisted} outside the expected patterns of "
          f"their relation), {sum(len(s) for s in res['runs'].values())} edges in three runs")
    (DIST / "chains-with-model.ttl").write_text(engine_inputs(res)["M1 product"], encoding="utf-8", newline="\n")
    print(f"round trip: {check_roundtrip(res)} statements read back from dist/chains.ttl give their source strings, "
          "weights, types and methods")
    return engine_check(res)


if __name__ == "__main__":
    raise SystemExit(main())
