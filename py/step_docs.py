def chains_page(res: dict) -> str:
    nodes, edges = res["nodes"], res["edges"]
    label = lambda k: nodes[k][1]  # noqa: E731
    fmt = lambda x: "-" if x is None else f"{x:.3f}"  # noqa: E731
    src = "\n".join(f"| {r['chain']} | {r['carrier_id']} | {r['potter']} | `{r['potform_text']}` | `{r['centre_text']}` |"
                    for r in res["rows"])
    hx = "\n".join(f"| {label(e['from'])} | `{e['role']}` | {label(e['to'])} | {e['weight']:g} | "
                   f"{e['type'] or '-'} | `{e['pattern']}` | {'yes' if e['listed'] else 'no'} |" for e in edges)
    comp = "\n".join(f"| `{c['relation']}` | {label(c['from'])} | {label(c['to'])} | {fmt(c['m1_product'])} | "
                     f"{fmt(c['m1_goedel'])} | {fmt(c['m2_product'])} |" for c in comparison(res))
    return f"""# Chains

Three chains from the CHNT data, one for each kind of imprecision, modelled as hextuples. The source strings
stand in [`data/chains-source.csv`]({T.BLOB}data/chains-source.csv); weight, FW type and method are computed
from them by `py/weights.py` (see [Weights](weights.html)). Two models are run over the same statements:

| Model | What is asserted | Carrier-centre link |
|---|---|---|
| M1 (the model of this repository) | `hasType`, `hasProductionCentre`, `worksAt` | asserted, as in the data export |
| M2 (`ontology/variant-b-derived.ttl`) | `hasType`, `createdBy` (crisp), `worksAt` | derived: `createdBy` o `worksAt` |

## The chains

| Chain | Carrier | Potter | Potform string | Centre string |
|---|---|---|---|---|
{src}

* **A** is vague without doubt: the potter worked at both centres (AND), the form is uncertain.
* **B** is an alternative: one centre or the other (OR), the form is uncertain.
* **C** combines both: three possible forms (OR) and two centres with a question mark (AND with `?`), which
  is fuzzy/wobbly.

{figure("05_chains", "Three chains with weights, FW types and derived degrees")}
## The hextuples of M1

| From | Role | To | Weight | FW type | Pattern | Expected on the relation |
|---|---|---|---|---|---|---|
{hx}

The generated file is `dist/chains.ttl`. The carrier-centre statements are inherited from the potter: they
carry the same weight and type as the potter-centre statements, and AND or OR is not in the list for that
relation (see question 11 of the [Review](review.html)).

## Derived degrees

Product is the logic of the ontology; Goedel is the minimum. M2 has no `carrierToActor`: the carrier-actor
link is asserted there (`createdBy`, 1.0), which is what the last column shows for it.

| Derived role | From | To | M1 product | M1 Goedel | M2 product |
|---|---|---|---|---|---|
{comp}

Reading the table:

* Where the doubt sits only at the potter (chain C, `carrierToActor`), M1 under product counts it twice,
  once on the carrier-centre statement and once on the actor-centre statement. M1 under Goedel and M2 do not.
* `potformToCentre` is the same in M1 and M2 under product: the form and the centre are two independent doubts.
* `potformToActor` is the weakest degree under M1 and product in chains B and C, because the same centre doubt is passed twice.
"""


def review_page() -> str:
    out = ["# Review\n", T.REVIEW_INTRO + "\n"]
    for i, (question, proposal, change) in enumerate(T.REVIEW_QUESTIONS, 1):
        out.append(f"### {i}. {question}\n\n- **Proposed:** {proposal}\n- **If not:** {change}\n")
    return "\n".join(out)


def main() -> int:
    g = load_graph(ONTOLOGY, TOY)
    model = read_model(g)
    state = reason(model, read_edges(g))
    res = run_chains()
    write("index.md", "Overview", index_page(model))
    write("model.md", "Model", model_page(model))
    write("vocabulary.md", "Vocabulary", vocabulary_page(model))
    write("reasoning.md", "Reasoning", reasoning_page(model, state))
    write("chains.md", "Chains", chains_page(res))
    write("weights.md", "Weights", weights_page())
    write("review.md", "Review", review_page())
    print("wrote docs/index.md, model.md, vocabulary.md, reasoning.md, chains.md, weights.md, review.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
