def figure(stem: str, alt: str) -> str:
    return (f"![{alt}](diagrams/{stem}.svg)\n\n"
            f"Source: [PNG](diagrams/{stem}.png) · drawn by `py/step_diagrams.py` from the ontology.\n")


def classify(model: dict) -> dict:
    """Kind of every role: asserted, inverse, derived, derived inverse, generic."""
    derived = {c for _, _, c, _ in model["chains"]}
    inverse_of = {ante: inv for _, ante, inv in model["inverses"]}
    kinds = {}
    for role in model["roles"]:
        if role in derived:
            kinds[role] = "derived (>>)"
        elif role == "reaches":
            kinds[role] = "generic (>>)"
        elif role == "reachedBy":
            kinds[role] = "generic inverse (<<)"
        elif role in inverse_of.values():
            origin = next(a for a, i in inverse_of.items() if i == role)
            kinds[role] = "derived inverse (<<)" if origin in derived else "inverse of an asserted role"
        else:
            kinds[role] = "asserted"
    return kinds


def plain(text: str) -> str:
    """Drop the trailing 'Inverse of x.' sentence; the table column already says it."""
    return re.sub(r"\s*Inverse of \w+\.$", "", text)


def partners(model: dict) -> dict:
    out = {}
    for _, ante, inv in model["inverses"]:
        out[ante], out[inv] = inv, ante
    return out


def page(title: str, body: str) -> str:
    return f"---\ntitle: {title}\n---\n\n{HEADER}\n{body.rstrip()}\n"


def write(name: str, title: str, body: str) -> None:
    DOCS.mkdir(parents=True, exist_ok=True)
    (DOCS / name).write_text(page(title, body), encoding="utf-8", newline="\n")


